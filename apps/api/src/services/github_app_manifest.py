"""GitHub's App manifest flow: build the manifest, sign its ``state``, and exchange the one-time ``code``.

Flow: a workspace admin asks for a manifest; the browser POSTs it to GitHub (``/settings/apps/new``, or the
organization's equivalent); the admin only clicks Create; GitHub redirects back with a one-time ``code`` that expires
after an hour; the API exchanges it (``POST /app-manifests/{code}/conversions``) for the App's id, slug, client id and
secret, webhook secret and private key, and stores them (github_app_credentials). The ``state`` is a short-lived JWT
bound to the admin who started it, so a code started by someone else, or a forged redirect, is refused; the code is
single-use on GitHub's side."""

from __future__ import annotations

import re
import secrets
import time
from urllib.parse import urlsplit

import httpx
import jwt

from src.core.config import settings
from src.routers.webhooks import _INGESTED_EVENT_TYPES
from src.services import app_permissions

STATE_PURPOSE = "github_app_manifest"
STATE_TTL_SECONDS = 3600  # GitHub's conversion code is valid for one hour
_ALG = "HS256"
_CODE_RE = re.compile(r"^[A-Za-z0-9_-]{1,200}$")
_ORG_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{0,38}$")


class ManifestError(RuntimeError):
    """A refusal to build the manifest or to exchange the code; the message is safe to show the admin."""


def web_base() -> str:
    """GitHub's web origin (where the manifest is posted), derived from the configured API base."""
    api = settings.github_api_base.rstrip("/")
    if api == "https://api.github.com":
        return "https://github.com"
    # GitHub Enterprise: https://host/api/v3 -> https://host
    return re.sub(r"/api/v3$", "", api)


def check_ui_origin(ui_origin: str) -> str:
    """The browser's UI origin must be one of the configured CORS origins: the redirect and setup URLs are built from
    it, so an arbitrary origin would let a manifest redirect the code to a page the operator never allowed."""
    origin = ui_origin.rstrip("/")
    allowed = {o.rstrip("/") for o in settings.cors_origins}
    parts = urlsplit(origin)
    if origin not in allowed or parts.scheme not in ("http", "https") or not parts.netloc or parts.path:
        raise ManifestError("This UI address is not listed in CORS_ORIGINS, so it cannot receive GitHub's redirect.")
    return origin


def build_manifest(*, ui_origin: str, api_base: str, name: str, read_only: bool) -> dict:
    """The manifest GitHub shows the admin. Permissions and events come from the same tables the app enforces
    (app_permissions, webhooks), URLs from the instance's own origins, so the "Setup URL left blank" failure cannot
    happen. The webhook secret is generated by GitHub and comes back in the conversion."""
    api = api_base.rstrip("/")
    return {
        "name": name,
        "url": ui_origin,
        "hook_attributes": {"url": f"{api}/webhooks/github", "active": True},
        "redirect_url": f"{ui_origin}/settings/github-app-callback",
        "callback_urls": [f"{api}/auth/github/callback"],
        "setup_url": f"{ui_origin}/settings/github-callback",
        "setup_on_update": True,
        "public": False,
        "request_oauth_on_install": False,
        "default_permissions": app_permissions.manifest_permissions(read_only),
        "default_events": sorted(_INGESTED_EVENT_TYPES),
    }


def post_url(organization: str | None, state: str) -> str:
    if organization:
        if not _ORG_RE.match(organization):
            raise ManifestError("That is not a valid GitHub organization name.")
        return f"{web_base()}/organizations/{organization}/settings/apps/new?state={state}"
    return f"{web_base()}/settings/apps/new?state={state}"


def sign_state(*, user_id: int, token_version: int, replace: bool, now: int | None = None) -> str:
    issued = int(now if now is not None else time.time())
    payload = {
        "purpose": STATE_PURPOSE,
        "uid": user_id,
        "tv": token_version,
        "rep": replace,
        "nonce": secrets.token_urlsafe(16),
        "iat": issued,
        "exp": issued + STATE_TTL_SECONDS,
    }
    return jwt.encode(payload, settings.auth_secret.get_secret_value(), algorithm=_ALG)


def verify_state(state: str, *, user_id: int, token_version: int) -> dict:
    """The state's claims, or ManifestError when it is forged, expired, for another purpose or another admin, or the
    admin signed out everywhere since starting."""
    try:
        claims = jwt.decode(state, settings.auth_secret.get_secret_value(), algorithms=[_ALG])
    except jwt.InvalidTokenError:
        raise ManifestError("This setup link has expired or is invalid. Start again from Settings.") from None
    if claims.get("purpose") != STATE_PURPOSE or claims.get("uid") != user_id or claims.get("tv") != token_version:
        raise ManifestError("This setup link was started by a different session. Start again from Settings.")
    return claims


def convert_code(code: str) -> dict:
    """Exchange the one-time code for the App's credentials (no authentication: the code is the credential)."""
    if not _CODE_RE.match(code):
        raise ManifestError("That is not a valid GitHub setup code.")
    base = settings.github_api_base.rstrip("/")
    try:
        resp = httpx.post(
            f"{base}/app-manifests/{code}/conversions",
            headers={"Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"},
            timeout=20,
        )
    except httpx.RequestError:
        raise ManifestError("GitHub could not be reached. Try again.") from None
    if resp.status_code != 201:
        raise ManifestError("GitHub refused the setup code (it may have expired or been used). Start again from Settings.")
    data = resp.json()
    needed = ("id", "slug", "client_id", "client_secret", "webhook_secret", "pem")
    if not isinstance(data, dict) or any(not data.get(k) for k in needed):
        raise ManifestError("GitHub's answer was missing the App's credentials.")
    return data
